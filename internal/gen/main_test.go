package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const want = `// Code generated by go run ./internal/gen; DO NOT EDIT.

// Package fixture is the legacy import path of example.com/new/fixture.
//
// Deprecated: use example.com/new/fixture instead.
package fixture

import sdk "example.com/new/fixture"

const ModeA = sdk.ModeA
const ModeB = sdk.ModeB

var Build = sdk.Build
var NewZeta = sdk.NewZeta

var DefaultName = sdk.DefaultName

type Alpha = sdk.Alpha
type Beta = sdk.Beta
type Gamma = sdk.Gamma
type Zeta = sdk.Zeta
`

func TestGenerateFixture(t *testing.T) {
	got, err := generate("testdata/fixture", "example.com/new/fixture")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Errorf("generate output mismatch\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

func TestGenerateRejectsGenericType(t *testing.T) {
	dir := t.TempDir()
	src := "package p\n\ntype Box[T any] struct{ v T }\n"
	if err := os.WriteFile(filepath.Join(dir, "p.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := generate(dir, "example.com/p")
	if err == nil || !strings.Contains(err.Error(), "generic type Box") {
		t.Fatalf("want generic type error, got %v", err)
	}
}

func TestGenerateRejectsEmptyPackage(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "p.go"), []byte("package p\n\nfunc hidden() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := generate(dir, "example.com/p"); err == nil {
		t.Fatal("want error for a package with no exported identifiers")
	}
}
