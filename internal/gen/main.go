// Command gen writes the legacy shim package signalhouse/shim.go, which
// re-exports every exported top-level identifier of the new SDK package as an
// alias. It is only runnable from the monorepo, where ../signalhouse exists.
//
// Regenerate (from sdks/golang/legacy):
//
//	go run ./internal/gen
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "// Code generated by go run ./internal/gen; DO NOT EDIT.\n\n"

// exports holds the exported top-level identifiers of one package, by kind.
type exports struct {
	pkgName string
	types   []string
	funcs   []string
	consts  []string
	vars    []string
}

func main() {
	src := flag.String("src", "../signalhouse", "directory of the package to re-export")
	out := flag.String("out", "signalhouse/shim.go", "file to write")
	importPath := flag.String("import", "github.com/signalhouse-sms/sdk-go/signalhouse", "import path of -src")
	flag.Parse()

	code, err := generate(*src, *importPath)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
}

// generate returns the gofmt-ed shim source that aliases every exported
// top-level identifier of the package in dir, imported as importPath.
func generate(dir, importPath string) ([]byte, error) {
	ex, err := collect(dir)
	if err != nil {
		return nil, err
	}
	if len(ex.types)+len(ex.funcs)+len(ex.consts)+len(ex.vars) == 0 {
		return nil, fmt.Errorf("%s: no exported identifiers", dir)
	}

	var b bytes.Buffer
	b.WriteString(header)
	fmt.Fprintf(&b, "// Package %s is the legacy import path of %s.\n", ex.pkgName, importPath)
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// Deprecated: use %s instead.\n", importPath)
	fmt.Fprintf(&b, "package %s\n\nimport sdk %q\n", ex.pkgName, importPath)

	section := func(names []string, line string) {
		if len(names) == 0 {
			return
		}
		b.WriteString("\n")
		for _, n := range names {
			fmt.Fprintf(&b, line, n, n)
		}
	}
	section(ex.consts, "const %s = sdk.%s\n")
	section(ex.funcs, "var %s = sdk.%s\n")
	section(ex.vars, "var %s = sdk.%s\n")
	section(ex.types, "type %s = sdk.%s\n")

	return format.Source(b.Bytes())
}

// collect parses the non-test Go files in dir that match the current build
// context and returns their exported top-level identifiers, each list sorted.
func collect(dir string) (exports, error) {
	var ex exports
	entries, err := os.ReadDir(dir)
	if err != nil {
		return ex, err
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		if ok, err := build.Default.MatchFile(dir, name); err != nil || !ok {
			if err != nil {
				return ex, err
			}
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return ex, err
		}
		if ex.pkgName == "" {
			ex.pkgName = f.Name.Name
		} else if ex.pkgName != f.Name.Name {
			return ex, fmt.Errorf("%s: packages %s and %s in one directory", dir, ex.pkgName, f.Name.Name)
		}
		if err := ex.add(fset, f); err != nil {
			return ex, err
		}
	}
	if ex.pkgName == "" {
		return ex, errors.New(dir + ": no Go files")
	}
	for _, s := range [][]string{ex.types, ex.funcs, ex.consts, ex.vars} {
		sort.Strings(s)
	}
	return ex, nil
}

// add records the exported top-level declarations of f. Methods are skipped
// because aliases carry them. A generic type fails, since go 1.21 cannot alias it.
func (ex *exports) add(fset *token.FileSet, f *ast.File) error {
	for _, decl := range f.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil && d.Name.IsExported() {
				if d.Type.TypeParams != nil {
					return fmt.Errorf("%s: generic func %s cannot be re-exported as a var", fset.Position(d.Pos()), d.Name)
				}
				ex.funcs = append(ex.funcs, d.Name.Name)
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						if s.TypeParams != nil {
							return fmt.Errorf("%s: generic type %s cannot be aliased under go 1.21", fset.Position(s.Pos()), s.Name)
						}
						ex.types = append(ex.types, s.Name.Name)
					}
				case *ast.ValueSpec:
					for _, n := range s.Names {
						if !n.IsExported() {
							continue
						}
						if d.Tok == token.CONST {
							ex.consts = append(ex.consts, n.Name)
						} else {
							ex.vars = append(ex.vars, n.Name)
						}
					}
				}
			}
		}
	}
	return nil
}
